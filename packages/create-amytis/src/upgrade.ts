// The versions after `from` up to `to` that the changelog lists, newest first,
// with each one's "### Upgrading…" section, if it has one.
export function releaseNotes(changelog: string, from: Version, to: Version): Array<{ version: string; upgrading?: string }> {
  const notes: Array<{ version: string; upgrading?: string }> = [];
  const sections = changelog.split(/^(?=## \[)/m);
  for (const section of sections) {
    const heading = /^## \[([^\]]+)\]/.exec(section);
    const version = heading ? parseVersion(heading[1]) : null;
    if (!version || compareVersions(version, from) <= 0 || compareVersions(version, to) > 0) continue;
    // Up to the next ## or ### heading; #### and deeper stay in the notes.
    const upgrading = /^### Upgrading.*\n([\s\S]*?)(?=^#{2,3}\s|$(?![\s\S]))/m.exec(section);
    notes.push({ version: version.join("."), upgrading: upgrading?.[1].trim() || undefined });
  }
  return notes;
}

