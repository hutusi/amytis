// Upgrading a site made with create-amytis to a newer Amytis release.
//
// A new site is a copy of one release with no git history in common with the
// Amytis repo, so `git merge` can't bring a newer release in. But the site's
// package.json keeps the version of the release it was made from, and every
// release stays downloadable, so the upgrade rebuilds that starting point and
// does what git would: a three-way merge of each file between the base
// release, the site and the target release. Files the site never changed take
// the new release's version, files the release never changed stay as the
// site has them, and only files both changed are merged.

