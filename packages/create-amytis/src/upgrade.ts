export interface UpgradeOptions {
  to?: string;
  from?: string;
  dryRun: boolean;
  force: boolean;
  install: boolean;
  baseDir?: string;
  targetDir?: string;
  help: boolean;
}

export function parseUpgradeArgs(args: string[]): UpgradeOptions {
  const options: UpgradeOptions = { dryRun: false, force: false, install: true, help: false };
  const value = (i: number, flag: string): string => {
    const v = args[i + 1];
    if (v === undefined || v.startsWith("-")) throw new Error(`${flag} needs a value`);
    return v;
  };
  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    switch (arg) {
      case "--to": options.to = value(i++, arg); break;
      case "--from": options.from = value(i++, arg); break;
      case "--base-dir": options.baseDir = value(i++, arg); break;
      case "--target-dir": options.targetDir = value(i++, arg); break;
      case "--dry-run": options.dryRun = true; break;
      case "--force": options.force = true; break;
      case "--no-install": options.install = false; break;
      case "--help": case "-h": options.help = true; break;
      default: throw new Error(`Unknown option: ${arg}`);
    }
  }
  return options;
}

function requireVersion(text: string, what: string): Version {
  const version = parseVersion(text);
  if (!version) throw new Error(`${what} "${text}" isn't an Amytis release version, such as v2.0.2`);
  return version;
}

function readVersion(dir: string): Version {
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, PACKAGE_JSON), "utf8")) as JsonObject;
  return requireVersion(String(pkg["version"]), `The version in ${path.join(dir, PACKAGE_JSON)}`);
}

type GitState = "clean" | "dirty" | "no-repo";

function gitState(dir: string): GitState {
  const result = spawnSync("git", ["status", "--porcelain", "--", "."], { cwd: dir, encoding: "utf8" });
  if (result.error || result.status !== 0) return "no-repo";
  return result.stdout.trim() ? "dirty" : "clean";
}

// Why git couldn't undo the plan by itself: the site isn't in git, has
// uncommitted changes, or the plan changes files that exist but that git
// doesn't track, such as ignored ones, which `git status` doesn't show.
// Files that don't exist yet are fine: undoing deletes them.
export type UndoProblem =
  | { kind: "no-repo" }
  | { kind: "dirty" }
  | { kind: "untracked"; paths: string[] };

export function undoProblem(siteDir: string, plan: UpgradePlan): UndoProblem | null {
  const state = gitState(siteDir);
  if (state !== "clean") return { kind: state };
  const listed = spawnSync("git", ["ls-files", "-z", "--", "."], { cwd: siteDir, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
  if (listed.error || listed.status !== 0) return { kind: "no-repo" };
  const tracked = new Set(listed.stdout.split("\0").filter(Boolean));
  const paths = plan.changes
    .flatMap(writtenPaths)
    .filter((rel) => !tracked.has(rel) && exists(path.join(siteDir, ...rel.split("/"))));
  return paths.length > 0 ? { kind: "untracked", paths } : null;
}

function undoProblemError(problem: UndoProblem): Error {
  switch (problem.kind) {
    case "no-repo":
      return new Error("This site isn't in a git repository, so the upgrade couldn't be undone. Commit it to git first (recommended), or pass --force.");
    case "dirty":
      return new Error("The site changed while the upgrade was getting ready, so nothing was changed. Commit, then run the upgrade again.");
    case "untracked":
      return new Error(
        "These files are in the site, but git doesn't track them (they may be ignored), so git couldn't undo " +
        `the upgrade's changes to them:\n  ${problem.paths.join("\n  ")}\n` +
        "Nothing was changed. Commit them or move them away, then run the upgrade again. Or pass --force.",
      );
  }
}

// How much of the base release's src/ the site has unchanged. A site made
// from that release keeps most of it even when customized; a low share means
// package.json's version isn't the release the site was made from.
export function shareUnchanged(siteDir: string, baseDir: string): number {
  if (!fs.existsSync(path.join(baseDir, "src"))) return 1;
  const files = listFiles(path.join(baseDir, "src")).map((rel) => `src/${rel}`).filter((rel) => !isEngineOnlyPath(rel));
  if (files.length === 0) return 1;
  const unchanged = files.filter((rel) => same(normalized(readFile(siteDir, rel)), normalized(readFile(baseDir, rel)))).length;
  return unchanged / files.length;
}

function printPlan(plan: UpgradePlan, verbose: boolean): void {
  const count = (kind: Change["kind"]) => plan.changes.filter((c) => c.kind === kind).length;
  const list = (kind: Change["kind"]) => plan.changes.filter((c) => c.kind === kind);

  if (verbose) {
    for (const kind of ["update", "add", "delete"] as const) {
      for (const change of list(kind)) console.log(`  ${kind.padEnd(8)} ${change.path}`);
    }
  }
  console.log(`  ${count("update")} files updated, ${count("add")} added, ${count("delete")} deleted.`);

  if (count("merged") > 0) {
    console.log("\n  Merged with your changes:");
    for (const change of list("merged")) console.log(`    ${change.path}`);
  }
  if (count("conflict") > 0) {
    console.log("\n  Conflicts to resolve (look for <<<<<<< in each file):");
    for (const change of list("conflict")) console.log(`    ${change.path} (${change.conflicts})`);
  }
  const kept = list("kept");
  if (kept.length > 0) {
    console.log("\n  Kept as you have them:");
    for (const change of kept) {
      const copy = change.newCopy ? `; the release's version is in ${sidecarOf(change)}` : "";
      console.log(`    ${change.path}: ${change.reason}${copy}`);
    }
  }
  if (plan.packageConflicts.length > 0) {
    console.log("\n  package.json: you and the release both changed these, so yours were kept:");
    for (const c of plan.packageConflicts) {
      console.log(`    ${c.key}: yours ${JSON.stringify(c.yours)}, the release's ${JSON.stringify(c.release)}`);
    }
  }
  if (plan.configNote) {
    console.log(`\n  site.config.ts was left alone: ${plan.configNote}.`);
  }
}

export const UPGRADE_USAGE = `Upgrade the Amytis site in this folder to a newer release:

  bunx create-amytis@latest upgrade [options]     (or: bun run upgrade)

Options:
  --to <version>       upgrade to this release instead of the latest
  --from <version>     the release the site was made from (default: package.json's version)
  --dry-run            list what would change, and change nothing
  --force              upgrade even with uncommitted changes, or outside git
  --no-install         don't run bun install afterwards
  --base-dir <dir>     use an unpacked release as the base instead of downloading it
  --target-dir <dir>   use an unpacked release as the target instead of downloading it
`;

// Returns the exit code: 0 when the upgrade went through cleanly, 1 when it
// left conflicts or kept files to look at, or bun install failed.
export async function upgrade(siteDir: string, options: UpgradeOptions): Promise<number> {
  if (options.help) {
    console.log(UPGRADE_USAGE);
    return 0;
  }
  for (const file of [PACKAGE_JSON, SITE_CONFIG]) {
    if (!fs.existsSync(path.join(siteDir, file))) {
      throw new Error(
        `There's no ${file} here. Run the upgrade in the folder of a site made with create-amytis. ` +
        `(To create a site named "upgrade", create it under another name and rename its folder.)`,
      );
    }
  }

  const sitePkg = JSON.parse(fs.readFileSync(path.join(siteDir, PACKAGE_JSON), "utf8")) as JsonObject;
  const baseVersion = options.from
    ? requireVersion(options.from, "--from")
    : options.baseDir
      ? readVersion(options.baseDir)
      : parseVersion(String(sitePkg["version"]));
  if (!baseVersion) {
    throw new Error(
      `package.json's version (${String(sitePkg["version"])}) isn't an Amytis release, so the release ` +
      `this site was made from is unknown. Pass it with --from, e.g. --from v2.0.2.`,
    );
  }

  if (!options.dryRun && !options.force) {
    const state = gitState(siteDir);
    if (state === "no-repo") {
      throw new Error(
        "This site isn't in a git repository, so the upgrade couldn't be undone. " +
        "Commit it to git first (recommended), or pass --force.",
      );
    }
    if (state === "dirty") {
      throw new Error(
        "You have uncommitted changes. Commit them first, so the upgrade is one change " +
        "you can review with git diff, and undo. Or pass --force.",
      );
    }
  }

  const scratchDir = fs.mkdtempSync(path.join(os.tmpdir(), "amytis-upgrade-"));
  try {
    let targetVersion: Version;
    if (options.targetDir) {
      targetVersion = readVersion(options.targetDir);
    } else if (options.to) {
      targetVersion = requireVersion(options.to, "--to");
    } else {
      console.log("Finding the latest Amytis release...");
      targetVersion = requireVersion(await getLatestReleaseTag(), "The latest release");
    }
    if (!options.baseDir && !options.targetDir) {
      const order = compareVersions(targetVersion, baseVersion);
      if (order === 0) {
        console.log(`This site is on Amytis ${tagOf(baseVersion)} already.`);
        return 0;
      }
      if (order < 0) {
        throw new Error(`${tagOf(targetVersion)} is older than ${tagOf(baseVersion)}, which this site is on. Downgrading isn't supported.`);
      }
    }

    const download = async (version: Version, name: string): Promise<string> => {
      console.log(`Downloading Amytis ${tagOf(version)}...`);
      return downloadRelease(tagOf(version), path.join(scratchDir, name));
    };
    const [baseDir, targetDir] = await Promise.all([
      options.baseDir ?? download(baseVersion, "base"),
      options.targetDir ?? download(targetVersion, "target"),
    ]);

    if (!options.from && !options.baseDir && shareUnchanged(siteDir, baseDir) < 0.5) {
      throw new Error(
        `Most of this site's src/ differs from Amytis ${tagOf(baseVersion)}, the version in package.json, ` +
        `so it was probably made from another release. Pass that one with --from, e.g. --from v2.0.2.`,
      );
    }

    const labels = { site: "your site", base: `Amytis ${tagOf(baseVersion)}`, target: `Amytis ${tagOf(targetVersion)}` };
    console.log(`\nUpgrading from Amytis ${tagOf(baseVersion)} to ${tagOf(targetVersion)}${options.dryRun ? " (dry run)" : ""}:\n`);
    const plan = planUpgrade({ siteDir, baseDir, targetDir, labels, scratchDir });
    if (plan.changes.length === 0 && !needsAttention(plan)) {
      console.log("  Nothing to change: the site has everything the release changed.");
      return 0;
    }
    // Checked again now, not only at the start: the downloads take a while,
    // and the site may have changed meanwhile.
    const problem = options.dryRun ? null : undoProblem(siteDir, plan);
    if (problem && !options.force) throw undoProblemError(problem);
    // When git can't undo it, list every file the upgrade touches.
    printPlan(plan, options.dryRun || problem !== null);

    if (options.dryRun) {
      console.log("\nDry run: nothing was changed.");
      return 0;
    }
    applyPlan(siteDir, plan);

    const changelog = readFile(targetDir, "CHANGELOG.md")?.toString("utf8");
    const notes = changelog ? releaseNotes(changelog, baseVersion, targetVersion) : [];
    for (const note of notes.filter((n) => n.upgrading).reverse()) {
      console.log(`\nUpgrading to ${note.version}, from CHANGELOG.md:\n\n${note.upgrading}`);
    }
    if (notes.length > 0) {
      console.log(`\nWhat's new in ${notes.map((n) => n.version).reverse().join(", ")}: see CHANGELOG.md.`);
    }

    let installFailed = false;
    if (options.install && plan.changes.length > 0) {
      console.log("\nInstalling dependencies (bun install)...");
      const install = spawnSync("bun", ["install"], { cwd: siteDir, stdio: "inherit" });
      if (install.error || install.status !== 0) {
        installFailed = true;
        const why = install.error ? install.error.message : `exit status ${install.status}`;
        console.error(`\nbun install failed (${why}). The files are upgraded, but the dependencies aren't.`);
      }
    }

    const attention = needsAttention(plan);
    const steps = ["Review the changes: git diff"];
    if (installFailed) steps.unshift("Install the new dependencies: bun install");
    if (attention) steps.push(`Resolve what's listed above, and delete the *${NEW_COPY_SUFFIX} files when done.`);
    steps.push("Check that the site still builds: bun run validate");
    console.log(`\nNext:\n${steps.map((step, i) => `  ${i + 1}. ${step}`).join("\n")}`);
    if (problem) {
      console.log("Git can't undo this upgrade by itself (it ran with --force); the files it changed are listed above.");
    } else {
      console.log("To undo the upgrade: git restore . and delete the new files git status lists, then run bun install.");
    }
    return attention || installFailed ? 1 : 0;
  } finally {
    fs.rmSync(scratchDir, { recursive: true, force: true });
  }
}
