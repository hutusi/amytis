export type Version = [number, number, number];

export function parseVersion(text: string): Version | null {
  const match = /^v?(\d+)\.(\d+)\.(\d+)$/.exec(text.trim());
  return match ? [Number(match[1]), Number(match[2]), Number(match[3])] : null;
}

export function compareVersions(a: Version, b: Version): number {
  return a[0] - b[0] || a[1] - b[1] || a[2] - b[2];
}

function tagOf(version: Version): string {
  return `v${version.join(".")}`;
}

// ---------------------------------------------------------------------------
// Which files an upgrade looks at
// ---------------------------------------------------------------------------

// The site's own: its writing, its images, and the build's image-hash cache.
const SITE_OWNED_DIRS = ["content/", "public/images/"];
const SITE_OWNED_FILES = new Set(["public/next-image-export-optimizer-hashes.json"]);
// Merged by their own rules (planPackageJson, planSiteConfig).
const PACKAGE_JSON = "package.json";
const SITE_CONFIG = "site.config.ts";
// Regenerated by `bun install` from the merged package.json.
const LOCKFILE = "bun.lock";
const LOCKFILE_KEPT = "bun install updates it";
// A site usually rewrites its README as its own, so a line-by-line merge with
// the Amytis README would only make noise.
const KEEP_YOURS = new Set(["README.md", "README.zh.md"]);
// Never part of a release. Skipped by name, whatever they are: in a linked
// git worktree, .git is a file.
const SKIP_NAMES = new Set([".git", "node_modules", ".next", "out"]);

function isSiteOwned(rel: string): boolean {
  return SITE_OWNED_DIRS.some((dir) => rel.startsWith(dir)) || SITE_OWNED_FILES.has(rel);
}

// Relative paths, with / separators, of the files under root.
export function listFiles(root: string): string[] {
  const files: string[] = [];
  const walk = (dir: string, prefix: string) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const rel = prefix + entry.name;
      if (SKIP_NAMES.has(entry.name)) continue;
      if (entry.isDirectory()) {
        walk(path.join(dir, entry.name), `${rel}/`);
      } else if (entry.isFile()) {
        files.push(rel);
      }
    }
  };
  walk(root, "");
  return files.sort();
}

function readFile(root: string, rel: string): Buffer | undefined {
  const file = path.join(root, ...rel.split("/"));
  return fs.existsSync(file) && fs.statSync(file).isFile() ? fs.readFileSync(file) : undefined;
}

// ---------------------------------------------------------------------------
// The three-way decision for one file
// ---------------------------------------------------------------------------

// Each version of a file; undefined where it doesn't exist. `base` is the
// file as the base release shipped it, `cleanBase` as a new site got it (the
// same, or missing for the engine's own tests and CI, which new sites don't
// get). The site counts as unchanged when it matches either.
export interface FileVersions {
  base?: Buffer;
  cleanBase?: Buffer;
  site?: Buffer;
  target?: Buffer;
}

export type Decision =
  | "none"            // nothing to do: the site already has it, or the release didn't change it
  | "take"            // the site never changed it: take the release's (or delete it)
  | "merge"           // both changed a text file: merge them
  | "keep-yours"      // both changed it, and it can't be merged: keep the site's
  | "release-deleted" // the release removed it, but the site changed it: keep the site's
  | "you-deleted";    // the site removed it, but the release changed it: leave it removed

function same(a: Buffer | undefined, b: Buffer | undefined): boolean {
  return a === undefined || b === undefined ? a === b : a.equals(b);
}

export function decideFile(v: FileVersions, mergeable: boolean): Decision {
  if (same(v.site, v.target)) return "none";
  if (same(v.site, v.base) || same(v.site, v.cleanBase)) return "take";
  if (same(v.target, v.base) || same(v.target, v.cleanBase)) return "none";
  if (v.target === undefined) return "release-deleted";
  if (v.site === undefined) return "you-deleted";
  return mergeable ? "merge" : "keep-yours";
}

// Git's test: a NUL byte in the first 8000 bytes.
function isBinary(buf: Buffer | undefined): boolean {
  return buf !== undefined && buf.subarray(0, 8000).includes(0);
}

// Line endings. Releases have LF, but a site cloned on Windows, where git's
// core.autocrlf is on by default, has CRLF. So text is compared and merged
// with LF, and written back with the line endings the site's file has.
// (latin1 maps each byte to one character, so the round trip keeps every
// other byte as it was; no UTF-8 sequence contains a CR or LF byte.)
function toLf(buf: Buffer): Buffer {
  return buf.includes("\r\n") ? Buffer.from(buf.toString("latin1").replace(/\r\n/g, "\n"), "latin1") : buf;
}

function normalized(buf: Buffer | undefined): Buffer | undefined {
  return buf === undefined || isBinary(buf) ? buf : toLf(buf);
}

function usesCrlf(buf: Buffer | undefined): boolean {
  if (buf === undefined || isBinary(buf)) return false;
  const text = buf.toString("latin1");
  const crlf = text.split("\r\n").length - 1;
  return crlf > 0 && crlf * 2 > text.split("\n").length - 1;
}

function withCrlf(buf: Buffer, crlf: boolean): Buffer {
  return crlf ? Buffer.from(buf.toString("latin1").replace(/\r?\n/g, "\r\n"), "latin1") : buf;
}

// The first part of rel, itself or a folder it's in, that is a symbolic link
// in the site; null if none is. The upgrade never writes through a link: it
// can lead out of the site, where git can't undo the change. `seen` caches
// what was looked up, as files share folders.
function linkOnPath(root: string, rel: string, seen: Map<string, boolean>): string | null {
  const parts = rel.split("/");
  for (let i = 1; i <= parts.length; i++) {
    const prefix = parts.slice(0, i).join("/");
    let isLink = seen.get(prefix);
    if (isLink === undefined) {
      try {
        isLink = fs.lstatSync(path.join(root, ...parts.slice(0, i))).isSymbolicLink();
      } catch {
        return null; // Doesn't exist (yet), so nothing below it does either.
      }
      seen.set(prefix, isLink);
    }
    if (isLink) return prefix;
  }
  return null;
}

export interface MergeLabels {
  site: string;
  base: string;
  target: string;
}

// `git merge-file`, which needs no repository. Null when git isn't installed.
export function mergeText(
  site: Buffer,
  base: Buffer | undefined,
  target: Buffer,
  labels: MergeLabels,
  scratchDir: string,
): { content: Buffer; conflicts: number } | null {
  const dir = fs.mkdtempSync(path.join(scratchDir, "merge-"));
  try {
    const files = { site: path.join(dir, "site"), base: path.join(dir, "base"), target: path.join(dir, "target") };
    fs.writeFileSync(files.site, site);
    fs.writeFileSync(files.base, base ?? "");
    fs.writeFileSync(files.target, target);
    const result = spawnSync(
      "git",
      ["merge-file", "-p", "-L", labels.site, "-L", labels.base, "-L", labels.target, files.site, files.base, files.target],
      { maxBuffer: 64 * 1024 * 1024 },
    );
    if (result.error) {
      if ((result.error as NodeJS.ErrnoException).code === "ENOENT") return null;
      throw result.error;
    }
    // The exit status is the number of conflicts, up to 127; above that, an error.
    if (result.status === null || result.status > 127) {
      throw new Error(`git merge-file failed: ${result.stderr.toString().trim()}`);
    }
    return { content: result.stdout, conflicts: result.status };
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

// ---------------------------------------------------------------------------
// package.json: a three-way merge by key
// ---------------------------------------------------------------------------

type Json = unknown;
type JsonObject = Record<string, Json>;

function isObject(value: Json): value is JsonObject {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

// Key order doesn't matter, so compare a canonical form.
function canonical(value: Json): Json {
  if (Array.isArray(value)) return value.map(canonical);
  if (isObject(value)) {
    return Object.fromEntries(Object.keys(value).sort().map((key) => [key, canonical(value[key])]));
  }
  return value;
}

function jsonEqual(a: Json, b: Json): boolean {
  return JSON.stringify(canonical(a)) === JSON.stringify(canonical(b));
}

export interface PackageConflict {
  key: string;
  yours: Json;
  release: Json;
}

// A key's own value: a key such as "constructor" isn't read from the prototype.
function own(value: Json, key: string): Json {
  return isObject(value) && Object.hasOwn(value, key) ? value[key] : undefined;
}

function mergeValue(
  key: string,
  base: Json,
  cleanBase: Json,
  site: Json,
  target: Json,
  conflicts: PackageConflict[],
): Json {
  if (jsonEqual(site, target)) return site;
  if (jsonEqual(site, base) || jsonEqual(site, cleanBase)) return target;
  if (jsonEqual(target, base) || jsonEqual(target, cleanBase)) return site;
  if (isObject(site) && isObject(target)) {
    const merged: JsonObject = {};
    const keys = [...Object.keys(site), ...Object.keys(target).filter((k) => !Object.hasOwn(site, k))];
    for (const k of keys) {
      const value = mergeValue(
        key ? `${key}.${k}` : k,
        own(base, k),
        own(cleanBase, k),
        own(site, k),
        own(target, k),
        conflicts,
      );
      // defineProperty, so a key such as "__proto__" stays a plain key.
      if (value !== undefined) Object.defineProperty(merged, k, { value, enumerable: true, writable: true, configurable: true });
    }
    return merged;
  }
  conflicts.push({ key, yours: site, release: target });
  return site;
}

// Merges the two releases' package.json into the site's. A key the site never
// changed takes the release's value (a dependency bump, a new script), a key
// the release never changed keeps the site's (a dependency the site added),
// and where both changed one value, the site's is kept and reported. The
// version always becomes the target's: it records which release the site is
// on, for the next upgrade.
export function mergePackageJson(
  base: JsonObject,
  site: JsonObject,
  target: JsonObject,
): { merged: JsonObject; conflicts: PackageConflict[] } {
  const name = typeof site["name"] === "string" ? site["name"] : "my-site";
  // The upgrade script is create-amytis's, not the release's, and sites made
  // before it was added don't have it. Left in, it would make an unchanged
  // release's scripts look different from the site's, so it is added after.
  const asSite = (pkg: JsonObject) => {
    const sitePkg = toSitePackage(pkg, name);
    if (isObject(sitePkg["scripts"])) delete sitePkg["scripts"]["upgrade"];
    return sitePkg;
  };
  const conflicts: PackageConflict[] = [];
  const merged = mergeValue(
    "",
    base,
    asSite(base),
    { ...site, version: base["version"] },
    asSite(target),
    conflicts,
  ) as JsonObject;
  if (target["version"] !== undefined) merged["version"] = target["version"];
  const scripts = merged["scripts"];
  if (isObject(scripts) && !Object.hasOwn(scripts, "upgrade")) scripts["upgrade"] = UPGRADE_SCRIPT;
  return { merged, conflicts };
}

