export interface Change {
  path: string;
  kind: "add" | "update" | "delete" | "merged" | "conflict" | "kept";
  write?: Buffer;     // the file's new content
  newCopy?: Buffer;   // the release's version, written beside it (see newCopyPath)
  newCopyPath?: string; // where: <path>.amytis-new, or <path>.2.amytis-new if that is taken
  conflicts?: number; // kind "conflict": how many
  reason?: string;    // kind "kept": why
}

export interface UpgradePlan {
  changes: Change[];
  packageConflicts: PackageConflict[];
  configNote?: string; // why site.config.ts was left alone
}

export const NEW_COPY_SUFFIX = ".amytis-new";

function planFile(rel: string, raw: FileVersions, labels: MergeLabels, scratchDir: string): Change | null {
  const keepYours = KEEP_YOURS.has(rel) || rel === LOCKFILE;
  const binary = isBinary(raw.base) || isBinary(raw.site) || isBinary(raw.target);
  // Compared and merged with LF; written with the site file's line endings.
  const lf = (buf: Buffer | undefined) => (binary ? buf : normalized(buf));
  const v: FileVersions = { base: lf(raw.base), cleanBase: lf(raw.cleanBase), site: lf(raw.site), target: lf(raw.target) };
  const crlf = usesCrlf(raw.site);
  const out = (buf: Buffer) => (binary ? buf : withCrlf(buf, crlf));
  const decision = decideFile(v, !keepYours && !binary);

  switch (decision) {
    case "none":
      return null;
    case "take":
      if (v.target === undefined) return v.site === undefined ? null : { path: rel, kind: "delete" };
      return { path: rel, kind: v.site === undefined ? "add" : "update", write: out(v.target) };
    case "merge": {
      const merged = mergeText(v.site!, v.base, v.target!, labels, scratchDir);
      if (!merged) {
        return { path: rel, kind: "kept", newCopy: out(v.target!), reason: "git isn't installed, so it couldn't be merged" };
      }
      return merged.conflicts > 0
        ? { path: rel, kind: "conflict", write: out(merged.content), conflicts: merged.conflicts }
        : { path: rel, kind: "merged", write: out(merged.content) };
    }
    case "keep-yours":
      if (rel === LOCKFILE) return { path: rel, kind: "kept", reason: LOCKFILE_KEPT };
      return { path: rel, kind: "kept", newCopy: out(v.target!), reason: binary ? "a binary file can't be merged" : "you rewrote it" };
    case "release-deleted":
      return { path: rel, kind: "kept", reason: "Amytis removed it, but you changed it" };
    case "you-deleted":
      return { path: rel, kind: "kept", newCopy: out(v.target!), reason: "you deleted it, and Amytis changed it" };
  }
}

function planPackageJson(siteDir: string, baseDir: string, targetDir: string): { change: Change | null; conflicts: PackageConflict[] } {
  const read = (dir: string) => JSON.parse(fs.readFileSync(path.join(dir, PACKAGE_JSON), "utf8")) as JsonObject;
  const siteText = fs.readFileSync(path.join(siteDir, PACKAGE_JSON), "utf8");
  const site = JSON.parse(siteText) as JsonObject;
  const target = read(targetDir);
  const { merged, conflicts } = mergePackageJson(read(baseDir), site, target);
  const text = JSON.stringify(merged, null, 2) + "\n";
  if (text === siteText.replace(/\r\n/g, "\n")) return { change: null, conflicts };
  // "update" when the result is just the release's, as a new site gets it.
  const asNewSite = toSitePackage(target, typeof site["name"] === "string" ? site["name"] : "my-site");
  const kind = jsonEqual(merged, asNewSite) ? "update" : "merged";
  const write = withCrlf(Buffer.from(text), usesCrlf(Buffer.from(siteText)));
  return { change: { path: PACKAGE_JSON, kind, write }, conflicts };
}

// The site's config began as the base release's starter config with its title
// and description filled in, so that is the merge base, and the target is the
// new starter with the same title and description. New config fields reach
// the site that way, and its own settings stay. Sites made before
// create-amytis 0.1.3 began from the demo site's own config instead, which
// isn't a base the new starter can be merged against; those are left alone.
function planSiteConfig(
  siteDir: string,
  baseDir: string,
  targetDir: string,
  labels: MergeLabels,
  scratchDir: string,
): { change: Change | null; note?: string } {
  const read = (dir: string, rel: string) => readFile(dir, rel)?.toString("utf8").replace(/\r\n/g, "\n");
  const siteRaw = readFile(siteDir, SITE_CONFIG);
  const site = read(siteDir, SITE_CONFIG);
  const starterBase = read(baseDir, "site.config.example.ts");
  const starterTarget = read(targetDir, "site.config.example.ts");
  if (site === undefined) return { change: null, note: "there is no site.config.ts" };
  if (starterBase === undefined || starterTarget === undefined) {
    return { change: null, note: "a release has no site.config.example.ts to compare it with" };
  }

  let base = starterBase;
  let target = starterTarget;
  const title = readConfigString(site, "title");
  const description = readConfigString(site, "description");
  if (title !== null && description !== null) {
    try {
      base = patchSiteConfigSource(starterBase, title, description);
      target = patchSiteConfigSource(starterTarget, title, description);
    } catch {
      base = starterBase;
      target = starterTarget;
    }
  }

  const demoBase = read(baseDir, SITE_CONFIG);
  if (demoBase !== undefined && lineDistance(site, demoBase) < lineDistance(site, base)) {
    return {
      change: null,
      note: "it began as the Amytis demo site's own config rather than the starter, so it can't be merged. " +
        "`git diff site.config.example.ts` shows what is new; copy what you need",
    };
  }

  const change = planFile(
    SITE_CONFIG,
    { base: Buffer.from(base), cleanBase: Buffer.from(starterBase), site: siteRaw, target: Buffer.from(target) },
    labels,
    scratchDir,
  );
  return { change };
}

export function planUpgrade(options: {
  siteDir: string;
  baseDir: string;
  targetDir: string;
  labels: MergeLabels;
  scratchDir: string;
}): UpgradePlan {
  const { siteDir, baseDir, targetDir, labels, scratchDir } = options;
  const paths = [...new Set([...listFiles(baseDir), ...listFiles(targetDir)])]
    .filter((rel) => !isSiteOwned(rel) && rel !== PACKAGE_JSON && rel !== SITE_CONFIG)
    .sort();

  const changes: Change[] = [];
  for (const rel of paths) {
    const engineOnly = isEngineOnlyPath(rel);
    const base = readFile(baseDir, rel);
    const change = planFile(
      rel,
      {
        base,
        cleanBase: engineOnly ? undefined : base,
        site: readFile(siteDir, rel),
        target: engineOnly ? undefined : readFile(targetDir, rel),
      },
      labels,
      scratchDir,
    );
    if (change) changes.push(change);
  }

  const pkg = planPackageJson(siteDir, baseDir, targetDir);
  if (pkg.change) changes.push(pkg.change);
  const config = planSiteConfig(siteDir, baseDir, targetDir, labels, scratchDir);
  if (config.change) changes.push(config.change);

  // The release's copy of a kept file goes beside it under a name the site
  // doesn't have yet, so an earlier upgrade's copy isn't overwritten.
  for (const change of changes) {
    if (change.newCopy) change.newCopyPath = freeSidecar(siteDir, change.path);
  }

  // A change that would write or delete through a symbolic link is left to
  // the site's owner instead.
  const seen = new Map<string, boolean>();
  const guarded = changes.map((change): Change => {
    const link = writtenPaths(change).map((rel) => linkOnPath(siteDir, rel, seen)).find((l) => l !== null);
    if (!link) return change;
    const what = link === change.path ? "it is a symbolic link" : `${link} is a symbolic link`;
    return { path: change.path, kind: "kept", reason: `${what}, and the upgrade doesn't write through links; Amytis changed it, so update it by hand` };
  });

  // So is one where a release turned a file into a folder, or the other way
  // round, and the site has something of its own in the way.
  const deleted = deletedPaths(guarded);
  const placed = guarded.map((change): Change => {
    const clash = pathClash(siteDir, change, deleted);
    return clash ? { path: change.path, kind: "kept", reason: `${clash}, so it was left as it is; sort it out by hand` } : change;
  });

  return { changes: placed, packageConflicts: pkg.conflicts, configNote: config.note };
}

function deletedPaths(changes: Change[]): Set<string> {
  return new Set(changes.filter((c) => c.kind === "delete").map((c) => c.path));
}

// Every file and link under dir, relative to the site.
function filesUnder(siteDir: string, rel: string): string[] {
  const found: string[] = [];
  for (const entry of fs.readdirSync(path.join(siteDir, ...rel.split("/")), { withFileTypes: true })) {
    const child = `${rel}/${entry.name}`;
    if (entry.isDirectory()) found.push(...filesUnder(siteDir, child));
    else found.push(child);
  }
  return found;
}

// Why a change can't be written where the site has a file in place of a
// folder the release needs, or a folder in place of a file; null if it can.
// Deletions happen first, so a folder the plan empties is no obstacle.
function pathClash(siteDir: string, change: Change, deleted: Set<string>): string | null {
  for (const rel of writtenPaths(change)) {
    if (change.kind === "delete" && rel === change.path) continue;
    const parts = rel.split("/");
    for (let i = 1; i < parts.length; i++) {
      const folder = parts.slice(0, i).join("/");
      let stat: fs.Stats;
      try {
        stat = fs.lstatSync(path.join(siteDir, ...parts.slice(0, i)));
      } catch {
        break; // Doesn't exist, so neither does anything below it.
      }
      if (!stat.isDirectory() && !deleted.has(folder)) {
        return `${folder} is a file in your site, where the new release has a folder`;
      }
    }
    let stat: fs.Stats | null = null;
    try {
      stat = fs.lstatSync(path.join(siteDir, ...parts));
    } catch {
      // Doesn't exist: nothing in the way.
    }
    if (stat?.isDirectory() && filesUnder(siteDir, rel).some((file) => !deleted.has(file))) {
      return `${rel} is a folder in your site, where the new release has a file`;
    }
  }
  return null;
}

function exists(file: string): boolean {
  try {
    fs.lstatSync(file);
    return true;
  } catch {
    return false;
  }
}

// <rel>.amytis-new, or <rel>.2.amytis-new and so on if that is taken. Every
// name ends in .amytis-new, so they are easy to find and delete.
function freeSidecar(siteDir: string, rel: string): string {
  for (let n = 1; ; n++) {
    const candidate = n === 1 ? `${rel}${NEW_COPY_SUFFIX}` : `${rel}.${n}${NEW_COPY_SUFFIX}`;
    if (!exists(path.join(siteDir, ...candidate.split("/")))) return candidate;
  }
}

function sidecarOf(change: Change): string {
  return change.newCopyPath ?? `${change.path}${NEW_COPY_SUFFIX}`;
}

// The paths in the site a change writes or deletes.
function writtenPaths(change: Change): string[] {
  const paths: string[] = [];
  if (change.kind === "delete" || change.write) paths.push(change.path);
  if (change.newCopy) paths.push(sidecarOf(change));
  return paths;
}

function removeEmptyDirs(dir: string, stopAt: string): void {
  while (dir !== stopAt && dir.startsWith(stopAt) && fs.existsSync(dir) && fs.readdirSync(dir).length === 0) {
    fs.rmdirSync(dir);
    dir = path.dirname(dir);
  }
}

export function applyPlan(siteDir: string, plan: UpgradePlan): void {
  const root = path.resolve(siteDir);
  // planUpgrade already leaves out changes through links. Checking again here,
  // before anything is written, keeps a plan made earlier, or by hand, from
  // writing out of the site.
  const seen = new Map<string, boolean>();
  for (const rel of plan.changes.flatMap(writtenPaths)) {
    const link = linkOnPath(root, rel, seen);
    if (link) throw new Error(`${link} in the site is a symbolic link; the upgrade won't write through it. Nothing was changed.`);
  }
  // A copy of the release's version never replaces a file.
  for (const change of plan.changes) {
    if (change.newCopy && exists(path.join(root, ...sidecarOf(change).split("/")))) {
      throw new Error(`${sidecarOf(change)} exists already, and the upgrade won't overwrite it. Nothing was changed.`);
    }
  }
  // Nor does a file go where the site has a folder, or into a "folder" that
  // is a file. planUpgrade keeps such changes for the owner already.
  const deleted = deletedPaths(plan.changes);
  for (const change of plan.changes) {
    const clash = pathClash(root, change, deleted);
    if (clash) throw new Error(`${change.path}: ${clash}. Nothing was changed.`);
  }

  // Deletions first, so a folder the release replaced with a file is gone
  // before the file is written.
  for (const change of plan.changes) {
    if (change.kind !== "delete") continue;
    const file = path.join(root, ...change.path.split("/"));
    fs.rmSync(file, { force: true });
    removeEmptyDirs(path.dirname(file), root);
  }
  for (const change of plan.changes) {
    const file = path.join(root, ...change.path.split("/"));
    if (change.write) {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, change.write);
    }
    if (change.newCopy) {
      const sidecar = path.join(root, ...sidecarOf(change).split("/"));
      fs.mkdirSync(path.dirname(sidecar), { recursive: true });
      fs.writeFileSync(sidecar, change.newCopy, { flag: "wx" });
    }
  }
}

// Whether the plan leaves something for the site's owner to look at.
export function needsAttention(plan: UpgradePlan): boolean {
  // A lockfile kept for bun install to update needs no look; one kept for any
  // other reason, such as being a symbolic link, does.
  const routine = (c: Change) => c.path === LOCKFILE && c.reason === LOCKFILE_KEPT;
  return plan.changes.some((c) => c.kind === "conflict" || (c.kind === "kept" && !routine(c))) ||
    plan.packageConflicts.length > 0 ||
    plan.configNote !== undefined;
}

