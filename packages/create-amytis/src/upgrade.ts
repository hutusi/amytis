// The value of a top-level string field, or the `en` value of a { en, zh }
// map; null when it has another shape.
export function readConfigString(src: string, field: string): string | null {
  const quoted = String.raw`("(?:[^"\\]|\\.)*")`;
  const match =
    new RegExp(String.raw`^ {2}${field}:\s*${quoted}`, "m").exec(src) ??
    new RegExp(String.raw`^ {2}${field}:\s*\{\s*en:\s*${quoted}`, "m").exec(src);
  if (!match) return null;
  try {
    return JSON.parse(match[1]) as string;
  } catch {
    return null;
  }
}

// How many lines differ between a and b, ignoring order.
function lineDistance(a: string, b: string): number {
  const counts = new Map<string, number>();
  for (const line of a.split("\n")) counts.set(line, (counts.get(line) ?? 0) + 1);
  for (const line of b.split("\n")) counts.set(line, (counts.get(line) ?? 0) - 1);
  let distance = 0;
  for (const n of counts.values()) distance += Math.abs(n);
  return distance;
}

