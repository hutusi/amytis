function buildSvg(src: IconSrc, name: string): string | null {
  const icon = src.icons[name];
  if (!icon) return null;
  const w = icon.width ?? src.width ?? 24;
  const h = icon.height ?? src.height ?? 24;
  // Iconify "body" is the inner content of the <svg> tag; wrap to get a full SVG.
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}">${icon.body}</svg>`;
}

export const ICON_DIR = path.join('src', 'assets', 'code-group-icons');
export const GLOBALS_CSS = path.join('src', 'app', 'globals.css');
export const BEGIN_MARKER = '/* === BEGIN: generated by scripts/generate-code-group-icons.ts — do not hand-edit === */';
export const END_MARKER = '/* === END: generated icons === */';

/** The generated rule block (markers included) for the given icon keys. */
export function buildCssBlock(keys: string[]): string {
  const lines = [BEGIN_MARKER];
  for (const key of keys) {
    lines.push(`.cg-tab[data-cg-icon="${key}"]::before {`);
    lines.push(`  content: '';`);
    lines.push(`  background-image: url("../assets/code-group-icons/${key}.svg");`);
    lines.push(`}`);
  }
  lines.push(END_MARKER);
  return lines.join('\n');
}

if (import.meta.main) {
  fs.mkdirSync(ICON_DIR, { recursive: true });
  const keys: string[] = [];
  for (const [key, { src, name }] of Object.entries(MAP)) {
    const svg = buildSvg(src, name);
    if (!svg) {
      throw new Error(`[generate-code-group-icons] Missing Iconify icon "${name}" for key "${key}"`);
    }
    fs.writeFileSync(path.join(ICON_DIR, `${key}.svg`), `${svg}\n`);
    keys.push(key);
  }

  const css = fs.readFileSync(GLOBALS_CSS, 'utf8');
  const start = css.indexOf(BEGIN_MARKER);
  const end = css.indexOf(END_MARKER);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`[generate-code-group-icons] Marker block not found in ${GLOBALS_CSS}`);
  }
  fs.writeFileSync(GLOBALS_CSS, css.slice(0, start) + buildCssBlock(keys) + css.slice(end + END_MARKER.length));
  console.log(`Wrote ${keys.length} icons to ${ICON_DIR} and updated ${GLOBALS_CSS}.`);
}
