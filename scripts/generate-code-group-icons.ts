/**
 * Generator for the code-group tab icons: writes each icon from Iconify's
 * logos / vscode-icons packs to src/assets/code-group-icons/<key>.svg and
 * rewrites the rule block between the BEGIN/END markers in
 * src/app/globals.css to reference them.
 *
 * Usage:
 *   bun scripts/generate-code-group-icons.ts
 *
 * The rules use relative `url()`s on purpose: the CSS pipeline resolves them
 * to content-hashed /_next/static/media/ files (immutable caching, basePath
 * aware), and a browser only fetches an icon when a tab with that key is on
 * the page. Inlining them as data URIs instead put ~47 KB (~18 KB gz) into
 * the render-blocking global stylesheet of every page.
 *
 * Each icon key here corresponds to a value returned by resolveCodeGroupIcon
 * in src/lib/code-group-icons.ts. Add to both files to support a new key.
 */
import fs from 'fs';
import path from 'path';
import { icons as logos } from '@iconify-json/logos';
import { icons as vscodeIcons } from '@iconify-json/vscode-icons';

type IconSrc = typeof logos | typeof vscodeIcons;

